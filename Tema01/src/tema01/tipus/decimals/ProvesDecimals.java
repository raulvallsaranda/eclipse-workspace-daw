package tema01.tipus.decimals;

public class ProvesDecimals {

	public static void main(String[] args) {
		
		//declaració de variables
		float preu = 33.00001F;
		
		double distancia = 309.340000001;
		
		byte distanciaEntera = (byte) distancia;
		
		System.out.println("Preu: "+preu);
		System.out.println("Distància: "+distancia);
		System.out.println("Distància entera: "+distanciaEntera);


	}

}
